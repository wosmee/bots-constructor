-- 0022: короткий публичный адрес платёжного вебхука вместо /pay/:botId/:webhookPath.
--
-- Зачем ОБЕ колонки (webhook_path и webhook_token):
--   webhook_path — старый непрозрачный путь (32 символа base36) из миграции 0018.
--     Колонка NOT NULL UNIQUE и остаётся в таблице: удалить колонку в D1 можно
--     только пересборкой таблицы, а старые строки всё ещё содержат значения.
--     Для маршрутизации вебхуков она БОЛЬШЕ НЕ используется: старый роут
--     /pay/:botId/:webhookPath отвечает 410 Gone без обращения к базе.
--   webhook_token — новый короткий код (10 символов, алфавит без 0/O/1/l/I),
--     глобально уникальный (bot id из URL исчез, поэтому уникальность на всю
--     таблицу). Публичный адрес вебхука теперь: https://<host>/p/<token>.
--     NULL у легаси-строк: им код выдаётся лениво (при открытии «Оплата» или
--     одноразовым бэкфиллом), ротация выдаёт новый код и инвалидирует старый.
ALTER TABLE payment_connections ADD COLUMN webhook_token TEXT;

-- Поиск подключения по публичному адресу — самый частый запрос из вебхука.
CREATE UNIQUE INDEX IF NOT EXISTS idx_payconn_token ON payment_connections(webhook_token);
