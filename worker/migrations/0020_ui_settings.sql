-- 0020: флаг «показывать продвинутые блоки в палитре».
--
-- Палитра выросла: кроме простых блоков (сообщение, кнопки, условие) в ней есть
-- редко используемые (счётчики, платежи, рассылки по сегментам). Новичку они
-- мешают — он ищет «Отправить сообщение» среди сорока строк. Флаг включает
-- отдельную секцию «Продвинутое» в интерфейсе; поведение сценариев он не меняет.
--
-- 0 = прежнее поведение (сейчас в проде): продвинутые блоки скрыты из основной
-- палитры. Значение по умолчанию именно 0, чтобы после миграции у всех
-- существующих аккаунтов вид редактора остался ровно таким же, как до неё, —
-- миграция не должна менять UI у тех, кто ничего не просил.
ALTER TABLE user_settings ADD COLUMN advanced_blocks INTEGER NOT NULL DEFAULT 0;
