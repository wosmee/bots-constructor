-- 0019: счётчики сценария (инкремент вместо пяти блоков) + дневной лимит рассылок.
--
-- Счётчик — это именованное число, привязанное к боту и к объекту:
--   scope 'user' — scope_id это Telegram user id клиента («сколько раз ЭТОТ
--     клиент нажал кнопку»);
--   scope 'bot'  — scope_id ВСЕГДА пустая строка '' («сколько всего в боте»),
--     потому что пользователя тут нет по определению. Пустая строка, а не
--     NULL: PRIMARY KEY в SQLite считает NULL-ы разными, и бот-счётчик
--     дублировался бы на каждой записи.
-- Значение может быть отрицательным: 'decrement' не зажимает ноль, иначе
-- «осталось 1 сообщение» нельзя было бы исправить вниз после отката. Кто хочет
-- нижнюю границу — проверяет её в сценарии, а не в хранилище.
--
-- Отдельная таблица вместо collection_items, потому что горячий путь: блоки
-- «Инкремент» / «Декремент» / «Проверить счётчик» должны делать ОДИН атомарный
-- UPSERT, а не искать и переписывать строку в произвольной авторской таблице.
CREATE TABLE IF NOT EXISTS counters (
  bot_id     TEXT NOT NULL,
  scope      TEXT NOT NULL CHECK (scope IN ('user','bot')),
  scope_id   TEXT NOT NULL,
  name       TEXT NOT NULL,
  value      INTEGER NOT NULL DEFAULT 0,
  updated_at INTEGER NOT NULL,
  PRIMARY KEY (bot_id, scope, scope_id, name)
);

-- Список всех счётчиков бота с одним именем: аналитика вида «сколько людей
-- собрали 5 приглашений» без сканирования таблицы.
CREATE INDEX IF NOT EXISTS idx_counters_bot_name ON counters(bot_id, name);

-- Дневной лимит сегментной рассылки (dailyCap).
-- Почему отдельная таблица, а не counters со scope 'bot': лимит нужен НА КАЖДЫЙ
-- день заново, то есть сущность — это пара (бот, дата), а не (бот, имя). В
-- counters пришлось бы каждый день придумывать новое имя вида 'bc:2026-09-23' —
-- строки никогда не очищались бы, а PK по имени мешал бы переиспользовать день.
-- Здесь счётчик живёт на бота (не на пользователя): dailyCap ограничивает
-- суммарный объём рассылки, иначе каждый получатель считался бы отдельно и
-- лимит никогда не срабатывал. day — дата в UTC формата YYYY-MM-DD: у бота нет
-- собственного часового пояса, а смещение воркера меняется, так что «сутки» тут
-- технические, а не календарные по Москве.
CREATE TABLE IF NOT EXISTS broadcast_counters (
  bot_id     TEXT NOT NULL,
  day        TEXT NOT NULL,
  sent       INTEGER NOT NULL DEFAULT 0,
  updated_at INTEGER NOT NULL,
  PRIMARY KEY (bot_id, day)
);
